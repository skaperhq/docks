import { access, readFile, readdir, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const outputPath = resolve(root, "THIRD_PARTY_NOTICES.md")
const rootPackage = JSON.parse(await readFile(resolve(root, "package.json")))

// These packages contribute browser code, generated CSS, fonts, or copied UI
// source to the self-contained distribution. Runtime dependencies are included
// as well so the published artifact has a single, conservative notice file.
const bundledUiRoots = [
  "@codemirror/lang-json",
  "@codemirror/language",
  "@codemirror/search",
  "@fontsource-variable/dm-sans",
  "@fontsource/dm-mono",
  "@lezer/highlight",
  "class-variance-authority",
  "clsx",
  "codemirror",
  "lucide-react",
  "radix-ui",
  "react",
  "react-dom",
  "shadcn",
  "tailwind-merge",
  "tailwindcss",
  "tw-animate-css",
]
const metadataOnlyRoots = new Set([
  ...Object.keys(rootPackage.dependencies ?? {}),
  "shadcn",
  "tailwindcss",
  "tw-animate-css",
])

const queue = [
  ...Object.keys(rootPackage.dependencies ?? {}),
  ...bundledUiRoots,
]
const packages = new Map()

while (queue.length) {
  const name = queue.shift()
  if (!name || packages.has(name)) continue

  const packageDirectory = resolve(root, "node_modules", name)
  const manifestPath = resolve(packageDirectory, "package.json")
  await access(manifestPath).catch(() => {
    throw new Error(
      `Cannot generate third-party notices because ${name} is not installed. Run npm ci first.`
    )
  })

  const manifest = JSON.parse(await readFile(manifestPath, "utf8"))
  const licenseText = await readLicenseText(packageDirectory)
  if (!licenseText) {
    throw new Error(
      `${name}@${manifest.version} has no discoverable license text.`
    )
  }

  packages.set(name, {
    name,
    version: manifest.version,
    license: normalizeLicense(manifest.license),
    text: licenseText,
  })

  if (!metadataOnlyRoots.has(name)) {
    for (const dependency of Object.keys({
      ...manifest.dependencies,
      ...manifest.optionalDependencies,
    })) {
      if (await isInstalled(dependency)) queue.push(dependency)
    }
  }
}

const sections = [...packages.values()]
  .sort((left, right) => left.name.localeCompare(right.name))
  .map(
    ({ name, version, license, text }) =>
      `## ${name}@${version}\n\nLicense: ${license}\n\n\`\`\`text\n${text}\n\`\`\``
  )

const output = `# Third-Party Notices

Skaper includes or distributes software and assets from the projects below.
The notices are generated by \`npm run notices\`; do not edit this file by hand.

${sections.join("\n\n---\n\n")}
`

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "")
  if (current !== output) {
    throw new Error(
      "THIRD_PARTY_NOTICES.md is out of date. Run npm run notices and commit the result."
    )
  }
} else {
  await writeFile(outputPath, output)
}

async function readLicenseText(packageDirectory) {
  const entries = await readdir(packageDirectory, { withFileTypes: true })
  const match = entries.find(
    (entry) =>
      entry.isFile() &&
      /^(?:licen[cs]e|copying|notice)(?:\.|$)/i.test(entry.name)
  )
  if (match)
    return (
      await readFile(resolve(packageDirectory, match.name), "utf8")
    ).trim()

  const readme = entries.find(
    (entry) => entry.isFile() && /^readme(?:\.|$)/i.test(entry.name)
  )
  if (!readme) return undefined

  const content = await readFile(resolve(packageDirectory, readme.name), "utf8")
  const heading = content.match(/^#{1,3}\s+licen[cs]e\s*$/im)
  return heading
    ? content.slice(heading.index + heading[0].length).trim()
    : undefined
}

async function isInstalled(name) {
  return access(resolve(root, "node_modules", name, "package.json"))
    .then(() => true)
    .catch(() => false)
}

function normalizeLicense(value) {
  if (typeof value === "string" && value.trim()) return value.trim()
  if (value && typeof value.type === "string") return value.type
  return "See license text"
}
